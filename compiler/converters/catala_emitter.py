"""
MudraForge Statutory Decompiler - Canonical Catala Language Emitter
===================================================================
Translates Declarative OKF v0.2 Abstract Syntax Trees (ASTs) generated by the
dual-stream neural decompiler into idiomatic, literate Catala source code (.catala_en).

Catala Reference:
  Merigoux, D., Chataing, N., & Protzenko, J. (2021).
  "Catala: A Programming Language for the Law", ACM PACMPL 5(ICFP):1-29.
  Specification: https://catala-lang.org/
"""

import re
from pathlib import Path
from typing import Any


def _to_snake_case(name: str) -> str:
    s = re.sub(r"[^\w\s]", "", str(name or "")).strip()
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = re.sub(r"([a-z])([A-Z])", r"\1_\2", s)
    s = re.sub(r"[\s\-]+", "_", s)
    return s.lower() or "statutory_rule"


def _to_pascal_case(name: str) -> str:
    clean = re.sub(r"[^\w\s\-]", " ", str(name or "")).strip()
    words = re.split(r"[\s_\-]+", clean)
    return "".join(w.capitalize() for w in words if w) or "StatutoryScope"


def _format_currency(amount: float | int, currency: str = "USD") -> str:
    amt = float(amount or 0)
    if amt.is_integer():
        formatted_num = f"{int(amt):,}"
    else:
        formatted_num = f"{amt:,.2f}"

    curr = str(currency or "USD").upper()
    if curr == "USD":
        return f"${formatted_num}"
    elif curr == "EUR":
        return f"{formatted_num} EUR"
    elif curr == "INR":
        return f"INR {formatted_num}"
    return f"{curr} {formatted_num}"


class CatalaEmitter:
    """
    Translates an OKF v0.2 statutory Abstract Syntax Tree into formal Catala (.catala_en) source.
    """

    def __init__(self, indent_size: int = 2):
        self.indent = " " * indent_size

    def emit(self, ast_or_result: dict[str, Any], title: str | None = None) -> str:
        # Unwrap synthesizedAst if full compiler output dict was passed
        ast = ast_or_result.get("synthesizedAst", ast_or_result)
        raw_text = ast.get("rawText") or ast_or_result.get("text") or ""
        rule_id = ast.get("ruleId") or ast_or_result.get("ruleId") or "StatutoryRule"
        pred_modality = (
            ast.get("predictedModality")
            or ast.get("modality")
            or ast_or_result.get("predictedModality")
            or "MODALITY_COMPUTATIONAL_CLIFF"
        )
        computation = ast.get("computation") or {}
        temporal = ast.get("temporalScope") or {}
        symbol_legend = ast.get("symbolLegend") or ast_or_result.get("symbolLegend") or {}

        scope_name = _to_pascal_case(rule_id)
        struct_name = f"{scope_name}Input"

        lines = []

        # 1. Literate Markdown Header
        doc_title = title or f"Statutory Formalization: {scope_name}"
        lines.append(f"# {doc_title}")
        lines.append("")
        if raw_text:
            clean_prose = raw_text.strip().replace("\n", " ")
            lines.append(f"> **Legislative Provision:**")
            lines.append(f"> \"{clean_prose}\"")
            lines.append("")
        lines.append("```catala")

        # 2. Input Structure Declaration
        lines.append(f"declaration structure {struct_name}:")
        input_fields = self._derive_input_fields(computation, symbol_legend, temporal)
        for field_name, field_type in input_fields:
            lines.append(f"{self.indent}data {field_name} content {field_type}")
        lines.append("")

        # 3. Scope Declaration
        lines.append(f"declaration scope {scope_name}:")
        lines.append(f"{self.indent}input input_data content {struct_name}")
        out_var, out_type = self._derive_output_signature(pred_modality)
        lines.append(f"{self.indent}output {out_var} content {out_type}")
        lines.append("")

        # 4. Scope Definition & Rules
        lines.append(f"scope {scope_name}:")
        scope_body = self._generate_scope_body(
            pred_modality=pred_modality,
            computation=computation,
            temporal=temporal,
            out_var=out_var,
        )
        for sline in scope_body:
            lines.append(f"{self.indent}{sline}")

        lines.append("```")
        lines.append("")
        return "\n".join(lines)

    def _derive_input_fields(
        self,
        computation: dict[str, Any],
        symbol_legend: dict[str, Any],
        temporal: dict[str, Any],
    ) -> list[tuple[str, str]]:
        fields = []
        base_name = _to_snake_case(computation.get("base") or "primary_amount")
        fields.append((base_name, "money"))

        if temporal.get("taxYear"):
            fields.append(("taxable_year", "integer"))
        if temporal.get("cutoverDate") or temporal.get("sunsetDate"):
            fields.append(("transaction_date", "date"))

        for sym, sym_meta in symbol_legend.items():
            s_name = _to_snake_case(sym)
            if s_name == base_name or any(f[0] == s_name for f in fields):
                continue
            catala_type = "money"
            type_tag = str(sym_meta.get("type", "")).upper()
            if "PERCENT" in type_tag or "RATE" in type_tag:
                catala_type = "decimal"
            elif "DURATION" in type_tag or "COUNT" in type_tag:
                catala_type = "integer"
            elif "FLAG" in type_tag or "BOOLEAN" in type_tag or "GUARD" in type_tag:
                catala_type = "boolean"
            fields.append((s_name, catala_type))

        if len(fields) == 1 and not any(f[0] == "is_resident" for f in fields):
            fields.append(("is_resident", "boolean"))

        return fields

    def _derive_output_signature(self, modality: str) -> tuple[str, str]:
        mod = str(modality).upper()
        if "COMPUTATIONAL" in mod:
            return ("calculated_assessment", "money")
        elif "PERMISSION" in mod:
            return ("is_permitted", "boolean")
        elif "PROHIBITION" in mod:
            return ("is_prohibited", "boolean")
        return ("verdict_established", "boolean")

    def _generate_scope_body(
        self,
        pred_modality: str,
        computation: dict[str, Any],
        temporal: dict[str, Any],
        out_var: str,
    ) -> list[str]:
        lines = []
        mod = str(pred_modality).upper()
        curr = computation.get("currency") or "USD"
        base_field = f"input_data.{_to_snake_case(computation.get('base') or 'primary_amount')}"

        rate_val = computation.get("rate")
        rate_pct = f"{rate_val * 100:.2f}%" if rate_val is not None else "0.0%"

        excess_thresh = computation.get("excessThreshold") or computation.get("threshold")
        cliff_thresh = computation.get("cliffThreshold")

        # 1. Temporal condition guard
        cond_lines = []
        if temporal.get("cutoverDate") and temporal.get("sunsetDate"):
            cond_lines.append(
                f"under condition input_data.transaction_date >= |{temporal['cutoverDate']}| and "
                f"input_data.transaction_date <= |{temporal['sunsetDate']}|"
            )
        elif temporal.get("taxYear"):
            cond_lines.append(f"under condition input_data.taxable_year = {temporal['taxYear']}")

        for cl in cond_lines:
            lines.append(cl)

        # 2. Modality Computational Excess
        if "EXCESS" in mod or computation.get("archetype") == "AST_EXCESS_THRESHOLD":
            thresh_fmt = _format_currency(excess_thresh or 0, curr)
            lines.append(f"definition {out_var} equals")
            lines.append(f"{self.indent}if {base_field} > {thresh_fmt} then")
            lines.append(f"{self.indent}{self.indent}({base_field} - {thresh_fmt}) * {rate_pct}")
            lines.append(f"{self.indent}else")
            lines.append(f"{self.indent}{self.indent}{_format_currency(0, curr)}")

        # 3. Modality Computational Cliff
        elif "CLIFF" in mod or computation.get("archetype") == "AST_CLIFF_THRESHOLD":
            cliff_val = cliff_thresh or excess_thresh or 0
            thresh_fmt = _format_currency(cliff_val, curr)
            lines.append(f"definition {out_var} equals")
            lines.append(f"{self.indent}if {base_field} >= {thresh_fmt} then")
            lines.append(f"{self.indent}{self.indent}{base_field} * {rate_pct}")
            lines.append(f"{self.indent}else")
            lines.append(f"{self.indent}{self.indent}{_format_currency(0, curr)}")

        # 4. Modality Progressive Slab
        elif "SLAB" in mod or "COMPOUND" in mod or computation.get("archetype") == "AST_PROGRESSIVE_SLAB":
            brackets = computation.get("brackets") or []
            if brackets and len(brackets) >= 2:
                lines.append(f"definition {out_var} equals")
                for idx, b in enumerate(brackets):
                    b_rate = f"{b.get('rate', 0.0) * 100:.2f}%"
                    b_cap = b.get("cap")
                    if b_cap is not None:
                        cap_fmt = _format_currency(b_cap, curr)
                        if idx == 0:
                            lines.append(f"{self.indent}if {base_field} <= {cap_fmt} then")
                            lines.append(f"{self.indent}{self.indent}{base_field} * {b_rate}")
                        else:
                            base_fixed = _format_currency(b.get("fixed", 0), curr)
                            prev_cap = _format_currency(brackets[idx - 1].get("cap", 0), curr)
                            lines.append(f"{self.indent}else if {base_field} <= {cap_fmt} then")
                            lines.append(f"{self.indent}{self.indent}{base_fixed} + ({base_field} - {prev_cap}) * {b_rate}")
                    else:
                        base_fixed = _format_currency(b.get("fixed", 0), curr)
                        prev_cap = _format_currency(brackets[idx - 1].get("cap", 0), curr)
                        lines.append(f"{self.indent}else")
                        lines.append(f"{self.indent}{self.indent}{base_fixed} + ({base_field} - {prev_cap}) * {b_rate}")
            else:
                flat_thresh = excess_thresh or cliff_thresh or 0
                if flat_thresh > 0:
                    lines.append(f"definition {out_var} equals")
                    lines.append(f"{self.indent}let capped_base = min {base_field} {_format_currency(flat_thresh, curr)} in")
                    lines.append(f"{self.indent}capped_base * {rate_pct}")
                else:
                    lines.append(f"definition {out_var} equals")
                    lines.append(f"{self.indent}{base_field} * {rate_pct}")

        # 5. Deontic Permission
        elif "PERMISSION" in mod:
            lines.append(f"definition {out_var} equals")
            lines.append(f"{self.indent}input_data.is_resident")

        # 6. Deontic Prohibition
        elif "PROHIBITION" in mod:
            lines.append(f"definition {out_var} equals")
            lines.append(f"{self.indent}true")

        # 7. Unresolved / Fail-Closed Default
        else:
            lines.append(f"definition {out_var} equals")
            lines.append(f"{self.indent}false")

        return lines


def emit_catala_code(ast_or_result: dict[str, Any], title: str | None = None) -> str:
    """
    Public entry point to convert an OKF v0.2 AST or decompiler result into Catala (.catala_en) source.
    """
    emitter = CatalaEmitter()
    return emitter.emit(ast_or_result, title=title)


def save_catala_file(ast_or_result: dict[str, Any], output_path: str | Path, title: str | None = None) -> Path:
    """
    Exports decompiled Catala source to a file.
    """
    out_p = Path(output_path)
    out_p.parent.mkdir(parents=True, exist_ok=True)
    code = emit_catala_code(ast_or_result, title=title)
    out_p.write_text(code, encoding="utf-8")
    return out_p
